#!/usr/bin/env python3
"""Converts an image to a C++ header of GRAY8 / RGB565 / RGB565_SWAPPED pixels.

  gray8           uint8_t, Pillow's "L" conversion
  rgb565          uint16_t, native order
  rgb565_swapped  uint16_t, byte-swapped (RRRRRGGG, GGGBBBBB in memory)

Example:
  tools/img2cpp.py assets/images/tg12864b.png image.hpp --format rgb565_swapped --name IMAGE
"""

import argparse
import pathlib
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import colorlib  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("input", type=pathlib.Path)
    ap.add_argument("output", type=pathlib.Path)
    ap.add_argument("--format", choices=["gray8", "rgb565", "rgb565_swapped"], default="rgb565_swapped")
    ap.add_argument("--name", default="IMAGE", help="name of the array")
    ap.add_argument("--width", type=int, help="expected width (error if different)")
    ap.add_argument("--height", type=int, help="expected height (error if different)")
    args = ap.parse_args()

    if args.format == "gray8":
        px = np.asarray(Image.open(args.input).convert("L"), dtype=np.uint8)
        ctype, fmt, per_line = "uint8_t", "{:3d}", 16
    else:
        px = colorlib.rgb888_to_rgb565(colorlib.load_rgb(args.input))
        if args.format == "rgb565_swapped":
            px = colorlib.byteswap16(px)
        ctype, fmt, per_line = "uint16_t", "0x{:04x}", 12
    h, w = px.shape[:2]
    if (args.width and w != args.width) or (args.height and h != args.height):
        raise SystemExit(f"{args.input}: size {w}x{h} != {args.width}x{args.height}")

    lines = [
        "// Generated by tools/img2cpp.py. Do not edit.",
        f"// Source: {args.input.name}, format: {args.format}",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"static const int {args.name}_WIDTH = {w};",
        f"static const int {args.name}_HEIGHT = {h};",
        f"static const {ctype} {args.name}[{h}][{w}] = {{",
    ]
    for y in range(h):
        lines.append("    {")
        lines += colorlib.c_array_rows(px[y], per_line, fmt, "        ")
        lines.append("    },")
    lines += ["};", ""]

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()

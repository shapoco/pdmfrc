#!/usr/bin/env python3
"""Converts a palette image (256x1 px) to a C++ header of uint8_t [256][3] (RGB888).

Pixel x of the palette is the apparent color of a pixel blinking at the ON
duty x / 255 (level x). Measure it on each display, e.g. by photographing the
gradient example.

Example:
  tools/pal2cpp.py assets/palettes/sg12864.png include/pdmfrc/palettes/sg12864.hpp --name SG12864
"""

import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import colorlib  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("palette", type=pathlib.Path)
    ap.add_argument("output", type=pathlib.Path)
    ap.add_argument("--name", default="PALETTE", help="name of the array")
    ap.add_argument("--namespace", default="pdmfrc::palettes", help="C++ namespace ('' for none)")
    args = ap.parse_args()

    pal = colorlib.load_palette(args.palette)

    ns = [n for n in args.namespace.split("::") if n]
    lines = [
        "// Generated by tools/pal2cpp.py. Do not edit.",
        f"// Source: {args.palette.name}",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
    ]
    lines += [f"namespace {n} {{" for n in ns]
    lines += [
        "",
        "// level (ON duty 0..255) -> apparent color (R, G, B)",
        f"static const uint8_t {args.name}[256][3] = {{",
    ]
    for i in range(0, 256, 4):
        lines.append("    " + " ".join(f"{{{r:3d}, {g:3d}, {b:3d}}}," for r, g, b in pal[i:i + 4]))
    lines += ["};", ""]
    lines += [f"}}  // namespace {n}" for n in reversed(ns)]
    lines.append("")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Builds a LUT (input pixel -> level) from a palette image and writes it as a C++ header.

Pass the array to Pdm::setLut() instead of calling Pdm::initLut() on targets
where building the LUT at run time is too slow (no FPU) or the RAM is short
(the array can stay in flash).

The algorithm is that of Pdm::initLut() but in floating point, so a color
almost equidistant from two palette entries may rarely map to another level.

Example:
  tools/mklut.py assets/palettes/tg12864b.png lut.hpp --format rgb565 --name TG12864B_LUT565
"""

import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import colorlib  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("palette", type=pathlib.Path)
    ap.add_argument("output", type=pathlib.Path)
    ap.add_argument("--format", choices=["rgb565", "gray8"], default="rgb565",
                    help="input format (rgb565 also serves RGB565_SWAPPED)")
    ap.add_argument("--name", default="LUT", help="name of the array")
    ap.add_argument("--rbits", type=int, default=4, help="PDMFRC_LUT565_R_BITS")
    ap.add_argument("--gbits", type=int, default=5, help="PDMFRC_LUT565_G_BITS")
    ap.add_argument("--bbits", type=int, default=4, help="PDMFRC_LUT565_B_BITS")
    args = ap.parse_args()

    pal = colorlib.load_palette(args.palette)
    if args.format == "rgb565":
        table = colorlib.Lut565(pal, args.rbits, args.gbits, args.bbits).table
        note = (f"// RGB565 LUT, R{args.rbits}G{args.gbits}B{args.bbits}: build the library with "
                f"PDMFRC_LUT565_R_BITS={args.rbits}, _G_BITS={args.gbits}, _B_BITS={args.bbits}")
    else:
        table = colorlib.lut_gray8(pal)
        note = "// GRAY8 LUT"

    lines = [
        "// Generated by tools/mklut.py. Do not edit.",
        f"// Source: {args.palette.name}",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        note,
        f"static const uint8_t {args.name}[{len(table)}] = {{",
    ]
    lines += colorlib.c_array_rows(table, 16, "{:3d}")
    lines += ["};", ""]

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
